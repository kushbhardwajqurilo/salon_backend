const auditLogSchema = new mongoose.Schema(
  {
    organizationId: {
      type: mongoose.Schema.Types.Mixed,
      ref: "Organization",
      default: null,
    },
    branchId: {
      type: mongoose.Schema.Types.Mixed,
      ref: "Branch",
      default: null,
    },
    actorId: {
      type: mongoose.Schema.Types.Mixed,
      ref: "User",
      default: null,
    },
    actorType: {
      type: String,
      enum: ["user", "system", "background_job", "integration"],
      default: "user",
    },
    action: {
      type: String,
      required: true,
      enum: Object.values(AUDIT_ACTIONS),
    },
    entityType: {
      type: String,
      required: true,
    },
    entityId: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },
    description: {
      type: String,
      required: true,
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
    source: {
      type: String,
      enum: ["web", "api", "system", "scheduled_job", "integration"],
      default: "api",
    },
    ipAddress: {
      type: String,
      default: null,
    },
    userAgent: {
      type: String,
      default: null,
    },
  },
  {
    timestamps: { createdAt: true, updatedAt: false },
  },
);

// Indexes
auditLogSchema.index({
  organizationId: 1,
  entityType: 1,
  entityId: 1,
  createdAt: -1,
});
auditLogSchema.index({ organizationId: 1, branchId: 1, createdAt: -1 });
// Partial filter unique index for idempotent audit recovery operations (such as attendance conflict recovery)
auditLogSchema.index(
  { organizationId: 1, action: 1, entityId: 1, "metadata.idempotencyKey": 1 },
  {
    unique: true,
    partialFilterExpression: {
      "metadata.idempotencyKey": { $exists: true },
    },
    name: "uniq_audit_idempotency_key",
  },
);

// Sanitize metadata on every save (protects both AuditLogService and direct new AuditLog/create paths)
auditLogSchema.pre("save", function () {
  if (this.metadata && typeof this.metadata === "object") {
    this.metadata = sanitizeAuditMetadata(this.metadata);
  }
});

// Enforce append-only immutability at the database-access layer
const immutableError = () =>
  new Error("AuditLog records are immutable and append-only");
for (const hook of [
  "updateOne",
  "updateMany",
  "findOneAndUpdate",
  "deleteOne",
  "deleteMany",
  "findOneAndDelete",
]) {
  auditLogSchema.pre(hook, function () {
    throw immutableError();
  });
}

export const AuditLog =
  mongoose.models.AuditLog || mongoose.model("AuditLog", auditLogSchema);
